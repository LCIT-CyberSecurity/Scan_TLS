"""Sign in with an LDAP / OpenLDAP password: LDAPS and StartTLS with a validated private CA, the failures, and the account rules.

Runs against the OpenLDAP lab container of the test stack (certificates generated by ops/dev/test-stack.sh).
"""
from __future__ import annotations

import json
import os
import uuid
from pathlib import Path

import httpx
import pytest
from ldap3 import Connection, Server

from conftest import API, wait_for

CA_FILE = os.environ.get("TEST_LDAP_CA_FILE", "")
pytestmark = pytest.mark.skipif(not (CA_FILE and Path(CA_FILE).exists()), reason="the OpenLDAP lab certificates are not available")
BASE = "dc=example,dc=org"
PEOPLE = f"ou=people,{BASE}"
ADMIN_DN, ADMIN_PW = f"cn=admin,{BASE}", "ldap-test-admin-pw"
PASSWORD = "Ldap-Passw0rd-Test!"


def ldap_cfg(**over):
    cfg = {"name": "lab", "server_url": "ldaps://openldap:636", "base_dn": PEOPLE, "login_attribute": "uid", "user_filter": "(objectClass=inetOrgPerson)",
           "bind_dn": ADMIN_DN, "starttls": False, "ca_pem": Path(CA_FILE).read_text(), "email_attribute": "mail", "name_attribute": "cn", "id_attribute": "uid"}
    return {"provider": "ldap", "ldap": {**cfg, **over}, "auto_provision": True}


@pytest.fixture(scope="module")
def directory():
    def connect():
        c = Connection(Server("openldap", port=389), user=ADMIN_DN, password=ADMIN_PW)
        assert c.bind()
        return c

    def up():
        try:
            connect().unbind()
            return True
        except Exception:  # noqa: BLE001
            return False

    wait_for(up, 90)
    c = connect()
    c.add(PEOPLE, "organizationalUnit")
    c.add(f"ou=sub,{PEOPLE}", "organizationalUnit")
    for uid in ("ldap-alice", "ldap-bob", "ldap-carol", "ldap-pending", "ldap-nomail"):
        attrs = {"cn": uid.title(), "sn": "T", "uid": uid, "userPassword": PASSWORD}
        if uid != "ldap-nomail":
            attrs["mail"] = f"{uid}@example.org"
        c.add(f"uid={uid},{PEOPLE}", "inetOrgPerson", attrs)
    c.add(f"uid=dup,{PEOPLE}", "inetOrgPerson", {"cn": "Dup One", "sn": "T", "uid": "dup", "mail": "dup1@example.org", "userPassword": PASSWORD})
    c.add(f"uid=dup,ou=sub,{PEOPLE}", "inetOrgPerson", {"cn": "Dup Two", "sn": "T", "uid": "dup", "mail": "dup2@example.org", "userPassword": PASSWORD})
    c.unbind()


@pytest.fixture(autouse=True)
def restore(admin, directory):
    yield
    admin.put("/api/admin/auth", json={"value": {"provider": "", "auto_provision": True}})


def configure(admin, value):
    r = admin.put("/api/admin/auth", json={"value": value})
    assert r.status_code == 200, r.text


def sign_in(username: str, password: str) -> tuple[httpx.Client, httpx.Response]:
    c = httpx.Client(base_url=API)
    return c, c.post("/api/auth/ldap/login", json={"username": username, "password": password})


def reasons(admin) -> list[str]:
    return [(e.get("detail") or {}).get("code") for e in admin.get("/api/admin/audit", params={"action": "auth.ldap_login", "limit": 10}).json()]


def test_ldaps_sign_in_creates_the_account_and_the_role_survives(admin):
    configure(admin, ldap_cfg())
    assert httpx.get(f"{API}/api/auth/providers").json()["ldap"] == {"enabled": True, "name": "lab"}
    c, r = sign_in("ldap-alice", PASSWORD)
    assert r.status_code == 200, r.text
    user = r.json()["user"]
    assert user["email"] == "ldap-alice@example.org" and user["role"] == "USER" and user["local_account"] is False
    assert c.get("/api/auth/me").status_code == 200                              # a normal TLS Scan session, same cookie and CSRF model
    assert admin.put(f"/api/admin/users/{user['id']}", json={"role": "OPERATOR"}).status_code == 200
    _, again = sign_in("ldap-alice", PASSWORD)
    assert again.json()["user"]["role"] == "OPERATOR" and again.json()["user"]["id"] == user["id"]
    row = next(u for u in admin.get("/api/admin/users").json() if u["id"] == user["id"])
    assert row["source"] == "ldap" and row["issuer"] == "ldap:lab"


def test_starttls_sign_in(admin):
    configure(admin, ldap_cfg(server_url="ldap://openldap:389", starttls=True))
    _, r = sign_in("ldap-bob", PASSWORD)
    assert r.status_code == 200, r.text


def test_plain_ldap_is_refused_at_configuration_time(admin):
    r = admin.put("/api/admin/auth", json={"value": ldap_cfg(server_url="ldap://openldap:389", starttls=False)})
    assert r.status_code == 422 and "plain LDAP" in r.text


def test_an_untrusted_certificate_is_never_accepted_silently(admin):
    configure(admin, ldap_cfg(ca_pem=""))                                         # no custom CA: the lab CA is unknown to the system store
    _, r = sign_in("ldap-alice", PASSWORD)
    assert r.status_code == 401
    assert reasons(admin)[0] == "ldap_tls"
    steps = {s["step"]: s for s in admin.post("/api/admin/auth/test/ldap", json={}).json()}
    assert steps["TLS / certificate"]["status"] == "fail" and "CA" in steps["TLS / certificate"]["detail"]


@pytest.mark.parametrize("login,password", [("ldap-alice", "wrong-password"), ("nobody-here", PASSWORD), ("ldap-alice", ""), ("", PASSWORD),
                                            ("*", PASSWORD), ("*)(uid=*", PASSWORD), ("ldap-alice)(|(uid=*", PASSWORD), ("ldap-alice\x00", PASSWORD), ("a" * 400, PASSWORD)])
def test_wrong_empty_and_malicious_logins_get_the_same_refusal(admin, login, password):
    configure(admin, ldap_cfg())
    _, r = sign_in(login, password)
    assert r.status_code == 401 and r.json() == {"detail": "Invalid credentials"}


def test_an_ambiguous_login_never_authenticates(admin):
    configure(admin, ldap_cfg())
    _, r = sign_in("dup", PASSWORD)
    assert r.status_code == 401
    assert reasons(admin)[0] == "ldap_ambiguous"


def test_an_unreachable_directory_is_a_clean_refusal(admin):
    configure(admin, ldap_cfg(server_url="ldaps://no-such-ldap.invalid:636"))
    _, r = sign_in("ldap-alice", PASSWORD)
    assert r.status_code == 401 and reasons(admin)[0] == "ldap_unreachable"
    steps = admin.post("/api/admin/auth/test/ldap", json={}).json()
    assert steps[-1]["step"] == "DNS" and steps[-1]["status"] == "fail"


def test_a_wrong_service_account_or_base_dn_is_explained(admin):
    configure(admin, ldap_cfg(bind_dn=f"cn=nobody,{BASE}"))
    steps = {s["step"]: s for s in admin.post("/api/admin/auth/test/ldap", json={}).json()}
    assert steps["service account bind"]["status"] == "fail"
    configure(admin, ldap_cfg(base_dn=f"ou=nowhere,{BASE}"))
    steps = {s["step"]: s for s in admin.post("/api/admin/auth/test/ldap", json={}).json()}
    assert steps["base DN"]["status"] == "fail" and "base DN" in steps["base DN"]["detail"]


def test_the_configuration_test_walks_every_step_and_never_leaks_the_password(admin):
    configure(admin, ldap_cfg())
    steps = admin.post("/api/admin/auth/test/ldap", json={"username": "ldap-carol", "password": PASSWORD}).json()
    assert [(s["step"], s["status"]) for s in steps] == [("configuration", "ok"), ("transport security", "ok"), ("DNS", "ok"), ("TCP connection", "ok"),
                                                         ("TLS / certificate", "ok"), ("service account bind", "ok"), ("base DN", "ok"), ("user search", "ok"),
                                                         ("user authentication", "ok")]
    untested = admin.post("/api/admin/auth/test/ldap", json={}).json()[-1]
    assert untested["step"] == "user authentication" and untested["status"] == "info"          # only run when explicitly asked
    for text in (json.dumps(steps), json.dumps(admin.get("/api/admin/auth").json()), json.dumps(admin.get("/api/admin/audit", params={"limit": 200}).json()),
                 json.dumps(admin.get("/api/admin/auth/diagnostics").json())):
        assert PASSWORD not in text and ADMIN_PW not in text


def test_a_disabled_account_and_a_missing_mail_are_refused(admin):
    configure(admin, ldap_cfg())
    c, r = sign_in("ldap-carol", PASSWORD)
    uid = r.json()["user"]["id"]
    assert admin.put(f"/api/admin/users/{uid}", json={"role": "USER", "active": False}).status_code == 200
    assert c.get("/api/auth/me").status_code == 401
    assert sign_in("ldap-carol", PASSWORD)[1].status_code == 401
    assert sign_in("ldap-nomail", PASSWORD)[1].status_code == 401


def test_pre_provisioned_people_are_adopted_and_nobody_else_enters_when_creation_is_off(admin):
    configure(admin, ldap_cfg(**{}) | {"auto_provision": False})
    assert sign_in("ldap-pending", PASSWORD)[1].status_code == 401
    assert admin.post("/api/admin/directory/provision", json={"email": "ldap-pending@example.org", "role": "AUDITOR"}).status_code == 201
    _, r = sign_in("ldap-pending", PASSWORD)
    assert r.status_code == 200 and r.json()["user"]["role"] == "AUDITOR"


def test_a_directory_account_never_takes_over_a_local_account_with_the_same_mail(admin):
    configure(admin, ldap_cfg())
    made = admin.post("/api/admin/users", json={"email": "ldap-bob2@example.org", "role": "ADMIN"})
    assert made.status_code == 201
    admin.put(f"/api/admin/users/{made.json()['user']['id']}", json={"role": "USER"})      # keep the shared administrator count unchanged
    c = Connection(Server("openldap", port=389), user=ADMIN_DN, password=ADMIN_PW)
    assert c.bind()
    c.add(f"uid=ldap-bob2,{PEOPLE}", "inetOrgPerson", {"cn": "Bob Two", "sn": "T", "uid": "ldap-bob2", "mail": "ldap-bob2@example.org", "userPassword": PASSWORD})
    c.unbind()
    assert sign_in("ldap-bob2", PASSWORD)[1].status_code == 401
    assert sum(1 for u in admin.get("/api/admin/users").json() if u["email"] == "ldap-bob2@example.org") == 1


def test_repeated_failures_are_throttled_like_the_local_sign_in(admin):
    # the lab stack runs with the limiter off (TLS_SCAN_RATE_LIMIT_ENABLED=false); the counters are the local ones, covered by test_login_throttle
    configure(admin, ldap_cfg())
    for _ in range(6):
        assert sign_in(f"nobody-{uuid.uuid4().hex[:4]}", "x")[1].status_code == 401
